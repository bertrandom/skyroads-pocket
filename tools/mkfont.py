# The music player's font (firmware/font6x11.h): Pillow's built-in bitmap
# font, characters 32 to 126, 6x11 pixels, one byte per row (bit 5 left).
#   python3 tools/mkfont.py > firmware/font6x11.h
from PIL import Image, ImageDraw, ImageFont

f = ImageFont.load_default_imagefont()
print("/* generated by tools/mkfont.py from Pillow's built-in bitmap font */")
print("#define FONT_W 6")
print("#define FONT_H 11")
print("static const unsigned char font6x11[95][11] = {")
for c in range(32, 127):
    im = Image.new("L", (6, 11), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), fill=255, font=f)
    rows = []
    for y in range(11):
        b = 0
        for x in range(6):
            if im.getpixel((x, y)) > 127:
                b |= 0x20 >> x
        rows.append("0x%02x" % b)
    name = chr(c).replace("\\", "backslash")
    print("    { %s }, /* %s */" % (", ".join(rows), "'" + name + "'" if c != 47 else "slash"))
print("};")
